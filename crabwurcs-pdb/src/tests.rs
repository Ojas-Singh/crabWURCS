//! Unit tests of the extractor.

use super::*;
use crabwurcs_core::{AnomericSymbol, ResidueKind, RingClosure};

#[allow(clippy::too_many_arguments)]
fn make_hetatm_line(
    serial: u32,
    atom_name: &str,
    res_name: &str,
    chain: &str,
    seq: u32,
    x: f64,
    y: f64,
    z: f64,
) -> String {
    let element = atom_name
        .chars()
        .find(char::is_ascii_alphabetic)
        .unwrap_or('C')
        .to_ascii_uppercase()
        .to_string();
    format!(
        "HETATM{:5} {:<4}{:1}{:3} {}{:4}{:1}   {:8.3}{:8.3}{:8.3}{:6.2}{:6.2}          {:>2}{:2}",
        serial, atom_name, "", res_name, chain, seq, "", x, y, z, 1.0f64, 0.0f64, element, ""
    )
}

#[test]
fn test_sugar_residue_detection() {
    assert!(is_sugar_name("NAG", true));
    assert!(is_sugar_name("MAN", true));
    assert!(is_sugar_name("FUC", true));
    assert!(!is_sugar_name("HOH", true));
    assert!(!is_sugar_name("ALA", false));
    // Amino acid names must not be classified as glycans even when they
    // look like a GLYCAM code (VAL would map to V + A = Ara + L).
    assert!(!is_sugar_name("VAL", false));
    // GLYCAM codes that begin with a linkage digit are sugars in ATOM
    // records too (GlycoShape writes every residue as ATOM).
    assert!(is_sugar_name("0aU", false));
    assert!(is_sugar_name("0FA", false));
    assert!(!is_sugar_name("VAL", false));
}

